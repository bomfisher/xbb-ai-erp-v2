-- 资金往来业务表设计
--
-- 适用范围：采购发票、应付款、付款单、预付款、付款核销及统一资金流水。
-- 执行事实源：实施时在 xbb-erp-app-admin/src/main/resources/db/migration/ 创建新的 Flyway 迁移。
-- 本文件是可读设计 SQL，不应直接作为已上线环境的迁移脚本执行。

CREATE TABLE `purchase_invoice` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `corpid` varchar(64) NOT NULL COMMENT '租户ID',
    `invoice_no` varchar(64) NOT NULL COMMENT '采购发票编号',
    `supplier_invoice_no` varchar(128) DEFAULT NULL COMMENT '供应商发票号码',
    `supplier_id` bigint(20) NOT NULL COMMENT '供应商ID',
    `invoice_date` bigint(20) NOT NULL COMMENT '发票日期',
    `due_date` bigint(20) DEFAULT NULL COMMENT '应付到期日',
    `payment_term` varchar(64) DEFAULT NULL COMMENT '付款条件',
    `untaxed_amount` decimal(18,2) NOT NULL DEFAULT '0.00' COMMENT '未税金额',
    `tax_amount` decimal(18,2) NOT NULL DEFAULT '0.00' COMMENT '税额',
    `amount` decimal(18,2) NOT NULL COMMENT '含税总金额',
    `invoice_type` varchar(32) NOT NULL DEFAULT 'PURCHASE' COMMENT '类型：PURCHASE、PURCHASE_RED',
    `status` varchar(32) NOT NULL COMMENT '状态：DRAFT、AUDITED、POSTED、VOIDED、RED_FLUSHED',
    `audit_status` tinyint(2) NOT NULL DEFAULT '0' COMMENT '审核状态：0待审核，1审核中，2已审核，3已拒绝',
    `audit_time` bigint(20) DEFAULT NULL COMMENT '审核时间',
    `posted_time` bigint(20) DEFAULT NULL COMMENT '过账时间',
    `original_invoice_id` bigint(20) DEFAULT NULL COMMENT '原采购发票ID，红冲时必填',
    `remark` varchar(255) DEFAULT NULL COMMENT '备注',
    `del` tinyint(2) NOT NULL DEFAULT '0',
    `add_time` bigint(20) NOT NULL,
    `update_time` bigint(20) NOT NULL,
    `creator_id` varchar(64) NOT NULL,
    `modify_id` varchar(64) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_purchase_invoice_no` (`corpid`, `invoice_no`),
    KEY `idx_purchase_invoice_supplier_date` (`corpid`, `supplier_id`, `invoice_date`),
    KEY `idx_purchase_invoice_status_due_date` (`corpid`, `status`, `due_date`),
    KEY `idx_purchase_invoice_supplier_invoice_no` (`corpid`, `supplier_id`, `supplier_invoice_no`),
    KEY `idx_purchase_invoice_original` (`corpid`, `original_invoice_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购发票';

CREATE TABLE `purchase_invoice_line` (
