CREATE TABLE `fund_transaction` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `corpid` varchar(64) NOT NULL COMMENT '租户ID',
    `transaction_no` varchar(64) NOT NULL COMMENT '系统资金流水号',
    `transaction_date` bigint(20) NOT NULL COMMENT '资金生效日期',
    `direction` varchar(8) NOT NULL COMMENT '方向：IN收入，OUT支出',
    `bank_account_id` bigint(20) NOT NULL COMMENT '资金账户ID，关联fund_account',
    `counterparty_type` varchar(32) NOT NULL COMMENT '往来对象类型：CUSTOMER、SUPPLIER',
    `counterparty_id` bigint(20) NOT NULL COMMENT '往来对象ID',
    `business_type` varchar(32) NOT NULL COMMENT '业务类型：RECEIPT、PAYMENT',
    `business_id` bigint(20) NOT NULL COMMENT '来源业务主表ID',
    `business_no` varchar(64) NOT NULL COMMENT '来源业务单号快照',
    `business_detail_id` bigint(20) NOT NULL COMMENT '来源收付款明细ID',
    `currency` varchar(16) NOT NULL DEFAULT 'CNY' COMMENT '资金账户币别快照',
    `amount` decimal(18,2) NOT NULL COMMENT '业务收付金额',
    `handling_fee` decimal(18,2) NOT NULL DEFAULT '0.00' COMMENT '手续费',
    `cash_amount` decimal(18,2) NOT NULL COMMENT '账户实际变动绝对额',
    `entry_type` varchar(16) NOT NULL DEFAULT 'NORMAL' COMMENT '分录类型：NORMAL、REVERSAL',
    `source_transaction_id` bigint(20) DEFAULT NULL COMMENT '原资金流水ID，冲正时必填',
    `status` varchar(16) NOT NULL DEFAULT 'POSTED' COMMENT '状态：POSTED、REVERSED',
    `remark` varchar(255) DEFAULT NULL COMMENT '备注',
    `del` tinyint(2) NOT NULL DEFAULT '0',
    `add_time` bigint(20) NOT NULL,
    `update_time` bigint(20) NOT NULL,
    `creator_id` varchar(64) NOT NULL,
    `modify_id` varchar(64) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_fund_transaction_no` (`corpid`, `transaction_no`),
    UNIQUE KEY `uk_fund_transaction_source` (`corpid`, `business_type`, `business_detail_id`, `entry_type`),
    KEY `idx_fund_transaction_account_date` (`corpid`, `bank_account_id`, `transaction_date`),
    KEY `idx_fund_transaction_direction_date` (`corpid`, `direction`, `transaction_date`),
    KEY `idx_fund_transaction_business` (`corpid`, `business_type`, `business_id`),
    KEY `idx_fund_transaction_counterparty` (`corpid`, `counterparty_type`, `counterparty_id`, `transaction_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='资金账户收支流水';
