CREATE TABLE `payable` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `corpid` varchar(64) NOT NULL COMMENT '租户ID',
    `payable_no` varchar(64) NOT NULL COMMENT '应付开放项编号',
    `supplier_id` bigint(20) NOT NULL COMMENT '供应商ID',
    `source_type` varchar(32) NOT NULL COMMENT '来源：PURCHASE_INVOICE、OPENING_BALANCE、MANUAL_ADJUSTMENT',
    `source_invoice_id` bigint(20) DEFAULT NULL COMMENT '来源采购发票ID',
    `opening_batch_id` bigint(20) DEFAULT NULL COMMENT '期初导入批次ID',
    `payable_date` bigint(20) NOT NULL COMMENT '应付确认日期',
    `due_date` bigint(20) DEFAULT NULL COMMENT '到期日',
    `amount` decimal(18,2) NOT NULL COMMENT '初始应付金额',
    `written_off_amount` decimal(18,2) NOT NULL DEFAULT '0.00' COMMENT '已核销金额',
    `remaining_amount` decimal(18,2) NOT NULL COMMENT '未核销应付余额',
    `status` tinyint(2) NOT NULL COMMENT '状态：未核销、部分核销、已核销、已关闭',
    `audit_status` tinyint(2) NOT NULL DEFAULT '0' COMMENT '审核状态：0待审核，1审核中，2已审核，3已拒绝',
    `remark` varchar(255) DEFAULT NULL COMMENT '备注',
    `del` tinyint(2) NOT NULL DEFAULT '0',
    `add_time` bigint(20) NOT NULL,
    `update_time` bigint(20) NOT NULL,
    `creator_id` varchar(64) NOT NULL,
    `modify_id` varchar(64) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_payable_no` (`corpid`, `payable_no`),
    UNIQUE KEY `uk_payable_invoice` (`corpid`, `source_invoice_id`),
    KEY `idx_payable_supplier_status` (`corpid`, `supplier_id`, `status`, `due_date`),
    KEY `idx_payable_source` (`corpid`, `source_type`, `source_invoice_id`),
    KEY `idx_payable_audit_status` (`corpid`, `audit_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='应付开放项';

CREATE TABLE `payment` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `corpid` varchar(64) NOT NULL COMMENT '租户ID',
    `payment_no` varchar(64) NOT NULL COMMENT '付款单编号',
    `supplier_id` bigint(20) NOT NULL COMMENT '供应商ID',
    `payment_date` bigint(20) NOT NULL COMMENT '付款日期',
    `amount` decimal(18,2) NOT NULL COMMENT '实际付款金额',
    `written_off_amount` decimal(18,2) NOT NULL DEFAULT '0.00' COMMENT '已核销金额',
    `remaining_amount` decimal(18,2) NOT NULL COMMENT '未核销付款余额',
    `payment_type` varchar(32) NOT NULL DEFAULT 'SUPPLIER_PAYMENT' COMMENT '付款类型：SUPPLIER_PAYMENT、ADVANCE_PAYMENT、OPENING_PAYMENT',
    `payment_method` varchar(32) DEFAULT NULL COMMENT '付款方式摘要',
    `bank_account_id` bigint(20) DEFAULT NULL COMMENT '付款资金账户ID摘要',
    `bank_transaction_no` varchar(128) DEFAULT NULL COMMENT '银行流水号或第三方交易号摘要',
    `status` tinyint(2) NOT NULL COMMENT '状态：未核销、部分核销、已核销、已关闭',
    `remark` varchar(255) DEFAULT NULL COMMENT '备注',
    `del` tinyint(2) NOT NULL DEFAULT '0',
    `add_time` bigint(20) NOT NULL,
    `update_time` bigint(20) NOT NULL,
    `creator_id` varchar(64) NOT NULL,
    `modify_id` varchar(64) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_payment_no` (`corpid`, `payment_no`),
    KEY `idx_payment_supplier_date` (`corpid`, `supplier_id`, `payment_date`),
    KEY `idx_payment_supplier_status` (`corpid`, `supplier_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应商付款开放项，含普通付款和预付款';

